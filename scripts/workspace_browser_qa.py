import asyncio,os,urllib.request
from pathlib import Path
from playwright.async_api import async_playwright
ROOT=Path(__file__).resolve().parent.parent
AXE_URL='https://cdnjs.cloudflare.com/ajax/libs/axe-core/4.10.2/axe.min.js'
AXE_CACHE=ROOT/'temp'/'axe.min.js'
def get_axe_src()->str:
 if not AXE_CACHE.exists():
  AXE_CACHE.parent.mkdir(parents=True,exist_ok=True)
  with urllib.request.urlopen(AXE_URL,timeout=30) as r: AXE_CACHE.write_bytes(r.read())
 return AXE_CACHE.read_text(encoding='utf-8')
async def check_axe(page,axe_js:str,label:str):
 await page.evaluate(axe_js)
 res=await page.evaluate("async () => await axe.run(document, {resultTypes: ['violations']})")
 viols=res.get('violations',[])
 assert not viols,f'axe violations at {label}: {[v["id"] for v in viols]}'
